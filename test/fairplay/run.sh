#!/usr/bin/env bash
# Differential test: app/source/fairplay.brs (in the brs emulator) vs the RPiPlay
# playfair C code (built unmodified, gcc -O2 and -O0).
#
# Usage: test/fairplay/run.sh [N] [SEED]
#   N     random (message3, ekey) decrypt vectors (default 40); additionally N/4 each of
#         handshake, sessionkey, sap_hash and modified_md5 component vectors, 4 setup
#         vectors and a set of fixed vectors (all 4 modes, zero / 0xff payloads, bad version).
#   SEED  PRNG seed for the vectors (default: random; printed)
# Env: RPIPLAY_LIB (default ../RPiPlay/lib), NODE (Node >= 20; Node 18 does not work).
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
LIB="${RPIPLAY_LIB:-$(cd "$ROOT/.." && pwd)/RPiPlay/lib}"
NODE="${NODE:-$HOME/.nvm/versions/node/v22.23.3/bin/node}"
BRS="$ROOT/tools/node/node_modules/brs-node/bin/brs.cli.js"
B="$HERE/build"
N="${1:-40}"
SEED="${2:-$(od -An -N4 -tu4 /dev/urandom | tr -d ' ')}"
mkdir -p "$B"

echo "== build C reference from $LIB"
for O in O2 O0; do
  gcc -$O -w -I"$LIB" -o "$B/harness_$O" "$HERE/harness.c" "$LIB/fairplay_playfair.c" "$LIB"/playfair/*.c -lm
done

echo "== check app/assets/fairplay is reproducible from the C sources"
rm -rf "$B/tables" && python3 "$ROOT/tools/gen_fairplay_tables.py" --out "$B/tables" "$LIB" >/dev/null
diff -r "$B/tables" "$ROOT/app/assets/fairplay" && echo "tables OK"

echo "== vectors: N=$N SEED=$SEED"
hdr_m=46504c590301030000000098   # "FPLY" 03 01 03 ... 98 : fp-setup phase-2 message (164 bytes)
hdr_e=46504c59010201000000003c00000000   # "FPLY" 01 02 01 ... 3c : ekey (72 bytes)
rep() { printf "%0.s$1" $(seq 1 "$2"); }
{
  for mode in 00 01 02 03; do
    echo "decrypt ${hdr_m}${mode}$(rep 00 151) ${hdr_e}$(rep 00 56)"
    echo "decrypt ${hdr_m}${mode}$(rep ff 151) ${hdr_e}$(rep ff 56)"
    echo "sessionkey ${hdr_m}${mode}$(rep 00 151)"
  done
  echo "decrypt 46504c59020103000000009802$(rep 5a 151) ${hdr_e}$(rep a5 56)"   # version byte not checked by decrypt
  echo "setup 46504c590201010000000004020000bb"                # version 2 -> invalid
  echo "handshake 46504c590201030000000098$(rep 11 152)"     # version 2 -> invalid
  echo "saphash $(rep 00 64)"
  echo "saphash $(rep ff 64)"
  echo "md5 $(rep 00 64) $(rep 00 16)"
  echo "md5 $(rep ff 64) $(rep ff 16)"
  "$B/harness_O2" gen "$N" "$SEED"
} > "$B/vectors.txt"
"$B/harness_O2" run < "$B/vectors.txt" > "$B/expected.txt"
"$B/harness_O0" run < "$B/vectors.txt" > "$B/expected_O0.txt"
cmp -s "$B/expected.txt" "$B/expected_O0.txt" || { echo "C reference differs between -O2 and -O0"; exit 1; }

{
  echo "function fp_test_vectors() as object"
  echo "    v = []"
  sed 's/.*/    v.push("&")/' "$B/vectors.txt"
  echo "    return v"
  echo "end function"
} > "$B/vectors.brs"

echo "== run BrightScript ($(wc -l < "$B/vectors.txt") vectors) in brs emulator"
start=$(date +%s%N)
(cd "$ROOT/app" && "$NODE" "$BRS" --root "$ROOT/app" \
   source/fairplay.brs ../test/fairplay/test_main.brs ../test/fairplay/build/vectors.brs) 2>&1 \
  | tr -d '\r' > "$B/brs_out.txt" || true   # the emulator prints CRLF
end=$(date +%s%N)
grep '^TIME' "$B/brs_out.txt" || true
grep -Ev '^(TIME|------|\s*$)' "$B/brs_out.txt" > "$B/actual.txt" || true
echo "emulator wall time: $(( (end - start) / 1000000 )) ms"

# Self-checking copy of some vectors for the real device (no emulator involved):
# put it next to app/source/fairplay.brs and call FairPlay_SelfTest().
{
  echo "' GENERATED by test/fairplay/run.sh (seed $SEED) -- on-device check of fairplay.brs."
  echo "' Copy into the app's source/ (with assets/fairplay) and call FairPlay_SelfTest()."
  echo "sub FairPlay_SelfTest()"
  echo "    v = []"
  paste -d' ' <(grep '^decrypt' "$B/vectors.txt") <(grep '^decrypt' "$B/expected.txt") \
    | awk 'NR <= 12 {printf "    v.push([\"%s\", \"%s\", \"%s\"])\n", $2, $3, $5}'
  cat <<'EOF'
    ts = CreateObject("roTimespan")
    ts.Mark()
    if fp_tables() = invalid then
        print "FAIRPLAY_SELFTEST FAIL: cannot load pkg:/assets/fairplay"
        return
    end if
    print "FAIRPLAY_SELFTEST tables_ms="; ts.TotalMilliseconds()
    fails = 0
    total = 0
    for each t in v
        m = CreateObject("roByteArray") : m.FromHexString(t[0])
        e = CreateObject("roByteArray") : e.FromHexString(t[1])
        ts.Mark()
        r = FairPlay_Decrypt(m, e)
        ms = ts.TotalMilliseconds()
        total = total + ms
        got = "invalid"
        if r <> invalid then got = LCase(r.ToHexString())
        if got <> t[2] then fails = fails + 1
        print "FAIRPLAY_SELFTEST decrypt ms="; ms; " "; got = t[2]
    end for
    print "FAIRPLAY_SELFTEST "; v.Count() - fails; "/"; v.Count(); " ok, avg_ms="; total \ v.Count()
end sub
EOF
} > "$B/device_selftest.brs"

if diff "$B/expected.txt" "$B/actual.txt" > "$B/diff.txt"; then
  echo "== PASS: $(wc -l < "$B/expected.txt") results identical ($(grep -c '^decrypt' "$B/expected.txt") decrypt), seed $SEED"
  echo "   device self-test written to $B/device_selftest.brs"
else
  echo "== FAIL (seed $SEED): $(grep -c '^>' "$B/diff.txt" || true) differing lines; first lines of $B/diff.txt:"
  head -20 "$B/diff.txt"
  exit 1
fi
